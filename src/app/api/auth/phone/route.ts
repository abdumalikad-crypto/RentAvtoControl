import { NextResponse } from 'next/server';
import { INITIAL_USERS } from '@/lib/mockData';
import { User } from '@/types';

let serverUsers: User[] = [...INITIAL_USERS];

export async function POST(request: Request) {
  try {
    const body = await request.json();
    const { phone, name, role = 'driver' } = body;

    if (!phone) {
      return NextResponse.json(
        { success: false, error: 'Telefon raqam kiritilishi shart' },
        { status: 400 }
      );
    }

    const cleanPhone = phone.replace(/\D/g, '');
    const randomSuffix = Math.floor(1000 + Math.random() * 9000);
    const autoGeneratedPassword = `IA-${cleanPhone.slice(-4)}-${randomSuffix}`;

    const existingUser = serverUsers.find((u) => u.phone === phone);

    if (existingUser) {
      return NextResponse.json({
        success: true,
        message: 'Tizimga muvaffaqiyatli kirdingiz (saqlangan parol bilan)',
        user: existingUser,
        autoPassword: existingUser.savedPasswordHash,
        isNewUser: false,
      });
    }

    const newUser: User = {
      id: `user-${role}-${Date.now()}`,
      name: name || (role === 'owner' ? 'Yangi Arendator' : 'Yangi Haydovchi'),
      phone,
      role: role as 'owner' | 'driver',
      passwordAutoSaved: true,
      savedPasswordHash: autoGeneratedPassword,
      balance: role === 'owner' ? 3000000 : 500000,
      rating: 5.0,
      activeContractsCount: 0,
      createdAt: new Date().toISOString().split('T')[0],
      avatar: 'https://images.unsplash.com/photo-1535713875002-d1d0cf377fde?w=150&auto=format&fit=crop&q=80',
    };

    serverUsers.unshift(newUser);

    return NextResponse.json({
      success: true,
      message: 'Telefon orqali registratsiya qilindi va parol avtomatik saqlandi',
      user: newUser,
      autoPassword: autoGeneratedPassword,
      isNewUser: true,
    });
  } catch (error) {
    return NextResponse.json(
      { success: false, error: 'Registratsiya xatosi' },
      { status: 500 }
    );
  }
}
